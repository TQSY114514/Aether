# lang → nav dict
nav_map = {
    'README.md': NAV_EN,
    'README.zh-CN.md': NAV_ZH_CN,
    'README.zh-TW.md': NAV_ZH_TW,
    'README.zh-WEN.md': NAV_ZH_WEN,
    'README.ja.md': NAV_JA,
    'README.es.md': NAV_ES,
    'README.fr.md': NAV_FR,
    'README.de.md': NAV_DE,
    'README.pt.md': NAV_PT,
    'README.ru.md': NAV_RU,
    'README.uk.md': NAV_UK,
    'README.ar.md': NAV_AR,
    'README.hi.md': NAV_HI,
    'README.ko.md': NAV_KO,
}

for f, nav in nav_map.items():
    p = os.path.join(BASE, f)
    if not os.path.exists(p):
        continue

    with open(p, 'r', encoding='utf-8') as fh:
        content = fh.read()

    lines = content.split('\n')

    # Find the navigation line (contains README.md and README.xx.md links)
    nav_line_idx = None
    for i, line in enumerate(lines):
        if 'README.md' in line and 'README.zh' in line and ('.md)' in line):
            nav_line_idx = i
            break

    if nav_line_idx is None:
        print(f"SKIP {f}: no nav line found")
        continue

    # Check if nav already has all 14 files
    has_all = all(x in lines[nav_line_idx] for x in ['zh-CN.md', 'zh-TW.md', 'zh-WEN.md', 'ja.md', 'es.md', 'fr.md', 'de.md', 'pt.md', 'ru.md', 'uk.md', 'ar.md', 'hi.md', 'ko.md'])

    if has_all:
        print(f"ALREADY DONE {f}")
        continue

    # Replace the nav line
    lines[nav_line_idx] = nav

    with open(p, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines))

    print(f"UPDATED {f}")
